"""The storage port used by ingestion and retrieval.

The application depends on this small interface, never on a concrete
filesystem or object-store client. That is what allows the local backend
used in development to be replaced by an object store later without
touching the API routes or the worker.

Keys are opaque, POSIX-style relative paths (for example
``uploads/<document_id>/original.pdf``). An adapter must reject a key
that is absolute or escapes its storage root; a key is never built from
a user-supplied filename.

Error contract:

* ``StorageUnavailableError`` - the backend could not be reached or the
  operation failed transiently. The API maps this to ``503``.
* ``StorageNotFoundError`` - the requested object does not exist. The
  API maps this to a missing-resource response, not a server error.
* ``StoragePathError`` - the key is invalid or escapes the root. This is
  a programming error and must never be caused by client input.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

__all__ = [
    "FileStorage",
    "StorageError",
    "StorageUnavailableError",
    "StorageNotFoundError",
    "StoragePathError",
]


class StorageError(Exception):
    """Base class for every storage-layer failure.

    Callers should catch this only when they want to handle all storage
    failures identically; otherwise catch one of the specific classes so
    a missing object is not confused with an unavailable backend.
    """


class StorageUnavailableError(StorageError):
    """The storage backend could not complete the operation.

    This covers connection failures, permission errors, a full disk, and
    other transient I/O problems. It is retryable at the API boundary and
    maps to ``503 DEPENDENCY_UNAVAILABLE``.
    """


class StorageNotFoundError(StorageError):
    """The requested object does not exist in the storage backend."""


class StoragePathError(StorageError, ValueError):
    """The storage key is invalid or escapes the storage root.

    This is deliberately a ``ValueError``: invalid keys are programming
    errors, and the previous local helpers also rejected them that way.
    It is never produced by a well-formed key generated by
    ``storage_key_for``.
    """


@runtime_checkable
class FileStorage(Protocol):
    """The operations an ingestion or retrieval caller needs.

    Implementations must be safe to call from a request thread. The
    local adapter is synchronous; a future object-store adapter may use a
    synchronous client as well. Async I/O is not part of this port.
    """

    def save(self, key: str, content: bytes) -> None:
        """Write ``content`` at ``key``, replacing any existing object.

        Implementations should write atomically: a reader must see either
        the old object or the complete new object, never a partial file.
        Raises ``StorageUnavailableError`` if the write cannot complete
        and ``StoragePathError`` if the key is invalid.
        """

    def read(self, key: str) -> bytes:
        """Return the complete object at ``key``.

        Raises ``StorageNotFoundError`` if the object does not exist,
        ``StorageUnavailableError`` if the backend cannot be read, and
        ``StoragePathError`` if the key is invalid.
        """

    def delete(self, key: str) -> bool:
        """Delete the object at ``key``.

        Returns ``True`` when an object was removed and ``False`` when it
        was already absent. Deleting a missing object is not an error, so
        a retried delete is idempotent. Raises
        ``StorageUnavailableError`` if the backend cannot complete the
        operation and ``StoragePathError`` if the key is invalid.
        """

    def exists(self, key: str) -> bool:
        """Return whether an object exists at ``key``.

        Raises ``StorageUnavailableError`` if the backend cannot be
        queried and ``StoragePathError`` if the key is invalid.
        """

    def size(self, key: str) -> int:
        """Return the object's size in bytes.

        Raises ``StorageNotFoundError`` if the object does not exist,
        ``StorageUnavailableError`` if the backend cannot be queried, and
        ``StoragePathError`` if the key is invalid.
        """
